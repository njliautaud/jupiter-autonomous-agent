#!/usr/bin/env python3
"""
mem_server — small token-auth HTTP API over the shared memory bus, for REMOTE agents
(other machines on your VPN/tailnet, cloud bots, CI jobs). Same store as `mem`.

Config (env or config/agent.env):
  MEM_BIND   address to bind (default 127.0.0.1). Set it to your VPN/tailnet
             interface address to reach it from other machines. NEVER a public IP.
  MEM_PORT   default 7692
  MEM_TOKEN  bearer token (required unless MEM_BIND is loopback). Generated by install.sh.

Auth: header `Authorization: Bearer <MEM_TOKEN>` on everything except /health.

Endpoints:
  GET  /health                       {ok, count}
  GET  /list                         [{slug,name,description,type,author,updated}]
  GET  /read?slug=SLUG               {slug,name,description,body,...}
  GET  /search?q=QUERY&limit=12      [{slug,description,score,...}]
  GET  /brief[?name=PROJECT]         {name,text} | {briefs:[...]}
  GET  /feed?n=25                    ["- <ts> · **who** · msg", ...]
  POST /write  {slug,description,body,type?,author?}
  POST /log    {msg,author?}
"""
import hmac, json, os, sys
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import urlparse, parse_qs
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import agentlib as A
import mem_core as M

BIND = A.env("MEM_BIND", "127.0.0.1")
PORT = A.env_int("MEM_PORT", 7692)
TOKEN = A.env("MEM_TOKEN", "")
MAX_BODY = 256 * 1024


def _int(q, k, d, hi):
    try:
        return max(1, min(hi, int(q.get(k, [d])[0])))
    except ValueError:
        return d


class H(BaseHTTPRequestHandler):
    server_version = "mem"
    sys_version = ""

    def setup(self):
        super().setup()
        self.request.settimeout(30)  # one slow client can never pin a worker forever

    def _send(self, code, obj):
        b = json.dumps(obj).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(b)))
        self.end_headers()
        self.wfile.write(b)

    def _auth(self):
        if not TOKEN:
            return True  # only possible on loopback (enforced at startup)
        h = self.headers.get("Authorization", "")
        got = h[7:].strip() if h.startswith("Bearer ") else ""
        return hmac.compare_digest(got.encode(), TOKEN.encode())

    def log_message(self, *a):
        pass

    def do_GET(self):
        u = urlparse(self.path); q = parse_qs(u.query)
        if u.path == "/health":
            return self._send(200, {"ok": True, "count": len(M.list_all())})
        if not self._auth():
            return self._send(401, {"error": "unauthorized"})
        if u.path == "/list":
            return self._send(200, M.list_all())
        if u.path == "/read":
            m = M.read(q.get("slug", [""])[0])
            return self._send(200 if m else 404, m or {"error": "not found"})
        if u.path == "/search":
            return self._send(200, M.search(q.get("q", [""])[0], _int(q, "limit", 12, 100)))
        if u.path == "/brief":
            name = q.get("name", [""])[0]
            if not name:
                return self._send(200, {"briefs": M.brief()})
            t = M.brief(name)
            return self._send(200 if t else 404, {"name": name, "text": t} if t else {"error": "not found"})
        if u.path == "/feed":
            return self._send(200, M.feed(_int(q, "n", 25, 500)))
        return self._send(404, {"error": "no route"})

    def do_POST(self):
        u = urlparse(self.path)
        if not self._auth():
            return self._send(401, {"error": "unauthorized"})
        try:
            n = int(self.headers.get("Content-Length", "0"))
            if n > MAX_BODY:
                return self._send(413, {"error": "body too large"})
            data = json.loads(self.rfile.read(n) or b"{}")
            assert isinstance(data, dict)
        except Exception as e:
            return self._send(400, {"error": f"bad json: {e}"})
        if u.path == "/write":
            for k in ("slug", "description", "body"):
                if not data.get(k):
                    return self._send(400, {"error": f"missing {k}"})
            try:
                res = M.write(str(data["slug"]), str(data["description"]), str(data["body"]),
                              str(data.get("type", "project")), str(data.get("author", "remote")))
            except ValueError as e:
                return self._send(400, {"error": str(e)})
            res.pop("path", None)
            return self._send(200, res)
        if u.path == "/log":
            if not data.get("msg"):
                return self._send(400, {"error": "missing msg"})
            M.log(str(data["msg"]), str(data.get("author", "remote")))
            return self._send(200, {"ok": True})
        return self._send(404, {"error": "no route"})


def main():
    loopback = BIND in ("127.0.0.1", "localhost", "::1")
    if not TOKEN and not loopback:
        sys.exit("mem_server: refusing to bind a non-loopback address without MEM_TOKEN (fail closed)")
    os.makedirs(M.MEM_DIR, exist_ok=True)
    print(f"mem_server on {BIND}:{PORT} (auth {'on' if TOKEN else 'off, loopback only'})", flush=True)
    ThreadingHTTPServer((BIND, PORT), H).serve_forever()


if __name__ == "__main__":
    main()
